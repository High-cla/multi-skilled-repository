#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Validate an extracted item catalog and emit the browser's items_data.js."""
import argparse
import json
import os
import tempfile
from pathlib import Path


def load_json(path: Path):
    raw = path.read_bytes()
    errors = []
    for encoding in ("utf-8-sig", "utf-16", "utf-16-le", "utf-16-be", "gbk"):
        try:
            return json.loads(raw.decode(encoding)), encoding
        except (UnicodeDecodeError, ValueError) as exc:
            errors.append(f"{encoding}: {exc}")
    raise ValueError("cannot decode JSON: " + "; ".join(errors))


def as_string(value, field, item_id):
    if value is None:
        return ""
    if isinstance(value, (str, int, float, bool)):
        return str(value)
    raise ValueError(f"{field} for item {item_id!r} must be a scalar or null")


def as_string_list(value, field, item_id):
    if value is None:
        return []
    values = value if isinstance(value, list) else [value]
    result = []
    for entry in values:
        if not isinstance(entry, (str, int, float, bool)):
            raise ValueError(f"{field} for item {item_id!r} must contain scalar values")
        result.append(str(entry))
    return result


def normalize_catalog(document):
    if isinstance(document, list):
        records = document
    elif isinstance(document, dict):
        records = document.get("records", document.get("items"))
    else:
        records = None
    if not isinstance(records, list) or not records:
        raise ValueError("catalog must be a non-empty array or an object with a non-empty records/items array")

    normalized = []
    seen = set()
    for index, record in enumerate(records):
        if not isinstance(record, dict):
            raise ValueError(f"record {index} must be an object")
        stable_id = record.get("stableId", record.get("stable_id", record.get("id")))
        if not isinstance(stable_id, (str, int)) or not str(stable_id).strip():
            raise ValueError(f"record {index} is missing a non-empty stableId/id")
        stable_id = str(stable_id)
        if stable_id in seen:
            raise ValueError(f"duplicate stableId: {stable_id}")
        seen.add(stable_id)

        item = dict(record)
        item["stableId"] = stable_id
        item["nameZh"] = as_string(record.get("nameZh", record.get("name", "")), "nameZh", stable_id)
        item["nameEn"] = as_string(record.get("nameEn", ""), "nameEn", stable_id)
        item["descriptionZh"] = as_string(record.get("descriptionZh", ""), "descriptionZh", stable_id)
        item["descriptionEn"] = as_string(record.get("descriptionEn", ""), "descriptionEn", stable_id)
        item["categories"] = as_string_list(record.get("categories"), "categories", stable_id)
        item["itemTypes"] = as_string_list(record.get("itemTypes"), "itemTypes", stable_id)
        normalized.append(item)
    return normalized


def write_js(items, output: Path):
    payload = json.dumps(items, ensure_ascii=False, separators=(",", ":"))
    # Escape JavaScript line separators and angle brackets defensively. The
    # output is an external .js file, but this also keeps future embedding safe.
    payload = (payload.replace("<", "\\u003c")
                      .replace(">", "\\u003e")
                      .replace("&", "\\u0026")
                      .replace("\u2028", "\\u2028")
                      .replace("\u2029", "\\u2029"))
    content = "// Generated by scripts/json_to_js.py; do not edit by hand.\nwindow.ITEMS = " + payload + ";\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=output.name + ".", suffix=".tmp", dir=str(output.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        os.replace(temp_name, output)
    except Exception:
        try:
            os.unlink(temp_name)
        except OSError:
            pass
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="extracted catalog JSON file")
    parser.add_argument("-o", "--output", type=Path,
                        default=Path(__file__).resolve().parent.parent / "assets" / "items_data.js")
    args = parser.parse_args(argv)
    document, encoding = load_json(args.input)
    items = normalize_catalog(document)
    write_js(items, args.output)
    print(f"converted {len(items)} items ({encoding}) -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
